#!/usr/bin/env python3
"""계약 타입을 손으로 다시 정의하지 않는다(D117 '같은 뜻의 타입은 한 번만 정의', C43, 워크스페이스 CLAUDE.md 스키마 배치: 계약에서 생성한 타입은
types/contract/(TS 는 src/types/contract/)에만 두고 사본을 두지 않는다, D104 구조 규칙 6).
왜: 계약 스키마와 같은 모양의 interface·TypedDict·dataclass 를 손으로 두면 계약이 바뀔 때 그 사본은 따라 바뀌지 않아 두 정의가 갈린다.
기준: 계약 패키지(../boundary-contracts/boundary_contracts/schemas/*.schema.json, 읽기 전용)의 최상위 properties 키 집합.
센다(손으로 쓴 코드: types/contract/·*validators.cjs·머리에 생성 표지가 있는 파일·시험 파일 밖):
  N 이름이 계약 스키마 이름과 같은 TS interface/type 객체 리터럴, 파이썬 TypedDict·dataclass·pydantic BaseModel·NamedTuple
  F 이름은 달라도 필드 집합이 어떤 계약 스키마의 properties 키 집합과 똑같은 것(필드 3개 이상: 2개 이하는 우연히 같기 쉽다)
생성 표지(머리 5줄): generated·자동 생성·생성물·DO NOT EDIT·손으로 고치지.
허용 목록(ALLOW, 빈 목록에서 시작). 사용: check-hand-contract-types.py [--self-test]. 종료 0 통과, 1 위반."""
import ast
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import _checklib as L  # noqa: E402

ALLOW = {}
GEN_MARK = re.compile(r"generated|자동 생성|생성물|DO NOT EDIT|손으로 고치지", re.I)
SCHEMAS = L.WS / "boundary-contracts/boundary_contracts/schemas"


def load_contracts(d=SCHEMAS):
    names, shapes = set(), {}
    for f in sorted(pathlib.Path(d).glob("*.schema.json")):
        n = f.name[:-len(".schema.json")]
        names.add(n)
        try:
            props = json.loads(f.read_text(encoding="utf-8")).get("properties")  # 헤드 점검 도구가 계약 파일을 읽는다(엄격 파서 대상 밖: 계약 자체)
        except ValueError:
            continue
        if isinstance(props, dict) and len(props) >= 3:
            shapes.setdefault(frozenset(props), n)
    return names, shapes


CONTRACTS = None


def contracts():
    global CONTRACTS
    if CONTRACTS is None:
        CONTRACTS = load_contracts()
    return CONTRACTS


def py_types(text):
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return []
    out = []
    for n in ast.walk(tree):
        if not isinstance(n, ast.ClassDef):
            continue
        bases = {ast.unparse(b).split(".")[-1] for b in n.bases}
        decos = {ast.unparse(d).split("(")[0].split(".")[-1] for d in n.decorator_list}
        if bases & {"TypedDict", "BaseModel", "NamedTuple"} or "dataclass" in decos:
            fields = {s.target.id for s in n.body if isinstance(s, ast.AnnAssign) and isinstance(s.target, ast.Name)}
            out.append((n.lineno, n.name, fields))
    return out


TS_DECL = re.compile(r"^\s*(?:export\s+)?(?:declare\s+)?(?:interface\s+(\w+)\b[^{=]*\{|type\s+(\w+)\s*(?:<[^=]*>)?\s*=\s*\{)")
TS_FIELD = re.compile(r"^\s*(?:readonly\s+)?[\"']?([A-Za-z_$][\w$-]*)[\"']?\s*\??\s*:")


def ts_types(text):
    lines = L.strip_js_comments(text)
    out = []
    for i, ln in enumerate(lines):
        m = TS_DECL.match(ln)
        if not m:
            continue
        name = m.group(1) or m.group(2)
        rest = "\n".join([ln[ln.index("{"):]] + lines[i + 1:i + 400])
        depth, end = 0, len(rest)
        for j, c in enumerate(rest):
            depth += (c == "{") - (c == "}")
            if depth == 0:
                end = j
                break
        body = rest[1:end]
        while re.search(r"\{[^{}]*\}", body):   # 안쪽 객체의 필드는 최상위 필드가 아니다
            body = re.sub(r"\{[^{}]*\}", "X", body)
        fields = {fm.group(1) for part in re.split(r"[;,\n]", body) if (fm := TS_FIELD.match(part))}
        out.append((i + 1, name, fields))
    return out


def scan(a, rel, text, cs=None):
    if L.generated(rel, text) or L.TEST_FILE.search(rel):
        return []
    names, shapes = cs or contracts()
    lg = L.lang(rel, text)
    types = py_types(text) if lg == "py" else ts_types(text) if lg == "js" and rel.endswith((".ts", ".tsx", ".mts", ".cts")) else []
    out = []
    for ln, name, fields in types:
        if name in names:
            out.append((ln, "N", f"계약 스키마 {name} 와 같은 이름의 손 정의 타입 — types/contract 생성물을 쓴다"))
        elif len(fields) >= 3 and frozenset(fields) in shapes:
            out.append((ln, "F", f"필드 집합이 계약 {shapes[frozenset(fields)]} 와 같은 손 정의 {name} — types/contract 생성물을 쓴다"))
    return out


def self_test():
    cs = ({"Session", "TurnRequest"}, {frozenset({"session_id", "turn", "text"}): "TurnRequest"})
    bad = []
    pos = [("src/a.ts", "export interface Session {\n  id: string;\n}\n"), ("src/a.ts", "type Mine = {\n  session_id: string;\n  turn: number;\n  text?: string;\n};\n"),
           ("p/a.py", "class Session(TypedDict):\n    id: str\n"), ("p/a.py", "@dataclass(frozen=True)\nclass X:\n    session_id: str\n    turn: int\n    text: str\n"),
           ("p/a.py", "class TurnRequest(BaseModel):\n    a: int\n"), ("src/a.ts", "export type Mine = { session_id: string; turn: number; text: string };\n")]
    neg = [("src/types/contract/Session.ts", "export interface Session {\n  id: string;\n}\n"), ("src/a.ts", "// generated by gen-types\nexport interface Session { id: string }\n"),
           ("src/a.ts", "type Mine = {\n  session_id: string;\n  turn: number;\n};\n"), ("p/a.py", "class Session:\n    pass\n"),
           ("p/a.py", "@dataclass\nclass X:\n    session_id: str\n    turn: int\n    text: str\n    extra: int\n"), ("tests/test_a.py", "class Session(TypedDict):\n    id: str\n"),
           ("src/a.ts", "import type { Session } from './types/contract/Session';\n")]
    for rel, t in pos:
        if not scan("z", rel, t, cs):
            bad.append(f"놓침 {rel} {t!r}")
    for rel, t in neg:
        if scan("z", rel, t, cs):
            bad.append(f"거짓양성 {rel} {t!r}")
    if SCHEMAS.is_dir() and not contracts()[0]:
        bad.append("계약 스키마를 하나도 읽지 못했다")
    return bad


if __name__ == "__main__":
    sys.exit(L.run("계약 타입 손 정의", scan, self_test, ALLOW, pathlib.Path(__file__).name))
