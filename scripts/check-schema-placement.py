def class_set(cls: str) -> str:
    """문자 클래스 안쪽을 글자 집합(정렬 문자열)으로: 범위 펼침, \\d·\\w 풀기, \\- 등 이스케이프 통일."""
    neg = cls.startswith("^")
    if neg:
        cls = cls[1:]
    items, i = [], 0
    while i < len(cls):
        c = cls[i]
        if c == "\\" and i + 1 < len(cls):
            n = cls[i + 1]
            i += 2
            if n == "d":
                items.extend("0123456789")
            elif n == "w":
                items.extend("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ_abcdefghijklmnopqrstuvwxyz")
            elif n.isalnum():
                items.extend("\\" + n)   # \s 등은 그대로(두 글자)
            else:
                items.append(n)
            continue
        if i + 2 < len(cls) and cls[i + 1] == "-" and cls[i + 2] != "\\":
            lo, hi = ord(c), ord(cls[i + 2])
            if lo <= hi:
                items.extend(chr(x) for x in range(lo, hi + 1))
                i += 3
                continue
        items.append(c)
        i += 1
    return ("^" if neg else "") + "".join(sorted(set(items)))


def norm(s: str) -> str:
    """정규식 표기 차이를 흡수한 열: 문자 클래스는 [정렬된 글자], \\d→[0-9], (?:·묶음 괄호 제거, 앵커 ^ $ \\A \\Z 와 꼬리 (?![\\s\\S]) 제거.
    수량자는 남긴다(flat 이 뺀다)."""
    out, i, n = [], 0, len(s)
    while i < n:
        c = s[i]
        if c == "\\" and i + 1 < n:
            x = s[i + 1]
            i += 2
            if x == "d":
                out.append("[" + class_set("0-9") + "]")
            elif x == "w":
                out.append("[" + class_set(r"\w") + "]")
            elif x in "AZz":
                pass
            elif x.isalnum():
                out.append("\\" + x)
            else:
                out.append(x)
        elif c == "[":
            j = i + 1
            if j < n and s[j] == "^":
                j += 1
            if j < n and s[j] == "]":
                j += 1
            while j < n and s[j] != "]":
                j += 2 if s[j] == "\\" else 1
            if j >= n:
                out.append(c)
                i += 1
            else:
                out.append("[" + class_set(s[i + 1:j]) + "]")
                i = j + 1
        elif s.startswith(r"(?![\s\S])", i):
            i += len(r"(?![\s\S])")
        elif s.startswith("(?:", i):   # 묶음 괄호는 표기 차이(비포획 여부)라 빼고 본다
            i += 3
        elif c in "^$()":
            i += 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def flat(s: str) -> str:
    return QUANT.sub("", norm(s))


def variants(s: str):
    """이중 이스케이프(\\\\)를 한 번 푼 것도 본다(코드 문자열 안의 패턴)."""
    yield s
    u = s.replace("\\\\", "\\")
    if u != s:
        yield u


def signature(pattern: str):
    """계약 패턴의 서명(정규화 후 수량자 제거). 문자 클래스가 CLASS_MIN 개 미만이면 None
    (한 클래스짜리는 우연히 같은 내부 형식이 많아 사본이라 단정할 수 없다)."""
    f = flat(pattern)
    if len(re.findall(r"\[[^\]]*\]", f)) < CLASS_MIN:
        return None
    return f


# 계약이 이미 버린 공개 형식(4.x 공개 SessionId). 문자 클래스가 하나라 서명으로 못 잡으므로 길이 수량자 {1,64} 까지 그대로 본다
LEGACY_NAME = "SessionId(4.x 공개 형식)"
LEGACY_SET = class_set("A-Za-z0-9_-")
LEGACY_RE = re.compile(r"\[((?:[^\]\\]|\\.)+)\]\{1,64\}")


def legacy_hits(s: str):
    return {LEGACY_NAME} if any(class_set(m) == LEGACY_SET for m in LEGACY_RE.findall(s)) else set()


def intersect_sig(parent: str, own: str):
    """부모 패턴이 [첫 글자][이후 글자] 두 클래스, 자기 패턴이 한 클래스일 때 교집합 형식 [첫∩자기][이후∩자기]. 이 모양이 아니면 None
    (일반 정규식 교집합은 계산하지 않는다)."""
    pf, of = flat(parent or ""), flat(own or "")
    pc, oc = re.findall(r"\[([^\]]*)\]", pf), re.findall(r"\[([^\]]*)\]", of)
    if len(pc) != 2 or len(oc) != 1 or re.sub(r"\[[^\]]*\]", "", of) or re.sub(r"\[[^\]]*\]", "", pf) \
            or any(x.startswith("^") for x in pc + oc):
        return None
    a = ["[" + "".join(sorted(set(c) & set(oc[0]))) + "]" for c in pc]
    return None if any(x == "[]" for x in a) else "".join(a)


def id_signatures(common=None):
    if common is None:
        try:
            common = json.loads((BC / "_common.schema.json").read_text(encoding="utf-8"))["$defs"]
        except (OSError, ValueError, KeyError) as e:
            raise ContractError(f"계약 _common 를 읽지 못했다: {type(e).__name__}")
    out = {}

    def pat(d, seen=0):
        if not isinstance(d, dict) or seen > 8:
            return None
        if "pattern" in d:
            return d["pattern"]
        r = d.get("$ref", "")
        if r.startswith("#/$defs/"):
            return pat(common.get(r.split("/")[-1]), seen + 1)
        for x in d.get("allOf", []):
            v = pat(x, seen + 1)
            if v:
                return v
        return None
    for n in ID_DEFS:
        sg = signature(pat(common.get(n)) or "")
        if sg:
            out.setdefault(sg, n)
        # 실효 패턴: $ref 로 Id 와 합쳐지면 두 패턴의 교집합 형식도 서명이다(계약에서 읽어 만든다, 하드코딩 아님)
        d = common.get(n)
        if isinstance(d, dict) and isinstance(d.get("pattern"), str) and str(d.get("$ref", "")).startswith("#/$defs/"):
            sg2 = intersect_sig(pat(common.get(d["$ref"].split("/")[-1])), d["pattern"])
            if sg2:
                out.setdefault(sg2, n)
    missing = [n for n in REQUIRED_SIGS if n not in out.values()]
    if not out or missing:
        raise ContractError(f"계약 ID 서명이 비었거나 빠졌다: {','.join(missing) or '전부'}")
    return out


