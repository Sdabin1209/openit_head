def pattern_nodes(node):
    """모든 노드의 pattern 값과 patternProperties 키. 같은 노드에 $ref 가 있어도 pattern 이 함께 있으면 사본으로 본다
    (위임은 pattern 없이 $ref·x-contract 만 둔 노드)."""
    if isinstance(node, dict):
        if isinstance(node.get("pattern"), str):
            yield node["pattern"]
        if isinstance(node.get("patternProperties"), dict):
            yield from node["patternProperties"].keys()
        for v in node.values():
            yield from pattern_nodes(v)
    elif isinstance(node, list):
        for v in node:
            yield from pattern_nodes(v)


def is_contract_ref(ref: str, names=frozenset()):
    """계약을 가리키는 $ref 인가: 로컬(#…)이 아니고, 경로에 boundary 계약 패키지 표지가 있거나 계약 파일 이름이다."""
    if not isinstance(ref, str) or ref.startswith("#"):
        return False
    path = ref.split("#", 1)[0]
    if re.search(r"(^|/)boundary(/|$)|boundary[_-]contracts", path):
        return True
    stem = re.sub(r"(\.schema)?\.json$", "", path.rsplit("/", 1)[-1])
    return stem == "_common" or stem in names


def defs_nodes(node):
    """$defs/definitions 의 (이름, 정의) 쌍."""
    if isinstance(node, dict):
        for k in ("$defs", "definitions"):
            if isinstance(node.get(k), dict):
                yield from node[k].items()
        for v in node.values():
            yield from defs_nodes(v)
    elif isinstance(node, list):
        for v in node:
            yield from defs_nodes(v)


def shape(s):
    """사본 판정 열쇠: 칸 이름·각 칸의 정의·required·additionalProperties 가 모두 같으면 사본이다(설명문은 뺀다).
    칸 이름만 같고 조건을 더하거나 바꾼 내부 스키마(계약을 받아들이는 조건 등)는 사본이 아니다."""
    if not isinstance(s, dict) or not isinstance(s.get("properties"), dict) or len(s["properties"]) < 2:
        return None   # 칸이 2개 미만인 스키마는 모양만으로 사본이라 할 수 없다
    def strip(n):
        if isinstance(n, dict):
            return {k: strip(v) for k, v in n.items() if k not in ("description", "title", "$id", "$comment", "examples")}
        return [strip(x) for x in n] if isinstance(n, list) else n
    return json.dumps({k: strip(s.get(k)) for k in ("properties", "required", "additionalProperties")}, sort_keys=True)


def contract():
    names, shapes = set(), {}
    for f in BC.glob("*.schema.json"):
        n = f.name[: -len(".schema.json")]
        names.add(n)
        sh = shape(json.loads(f.read_text(encoding="utf-8")))
        if sh:
            shapes[sh] = n
    return names, shapes


def strip_comment(line: str, base: str):
    """줄 끝 주석을 자른다(따옴표 밖의 # 또는 //). 줄 전체가 주석이면 빈 문자열. 이스케이프된 백슬래시 뒤 따옴표도 따라간다."""
    hash_ok = base.endswith((".py", ".sh", ".caddy")) or base == "Caddyfile"
    slash_ok = base.endswith((".ts", ".mjs", ".js", ".go"))
    q, i = None, 0
    while i < len(line):
        c = line[i]
        if q:
            if c == "\\":
                i += 2   # \\ 와 \" 는 한 쌍으로 건너뛴다
                continue
            if c == q:
                q = None
        elif c in "\"'`":
            q = c
        elif hash_ok and c == "#" and (i == 0 or line[i - 1].isspace()):
            return line[:i]
        elif slash_ok and c == "/" and line[i + 1:i + 2] == "/":
            return line[:i]
        i += 1
    return line


def py_docstring_lines(text: str):
    """Python ast 가 정의하는 docstring(모듈·클래스·함수 본문 첫 문장의 문자열)의 줄 번호. 대입·호출 인자의 삼중 따옴표 문자열은 코드다.
    파싱에 실패하면 아무것도 빼지 않고 전부 본다."""
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return set()
    out = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
                out.update(range(first.lineno, first.end_lineno + 1))
    return out


def code_lines(text: str, base: str):
    """주석이 아닌 줄들(# // /* */ 제외). 정규식은 주석에 적힌 설명이 아니라 코드에 있는 것만 센다."""
    in_block, n_line = False, 0
    doc_lines = py_docstring_lines(text) if base.endswith(".py") else set()
    for raw in text.splitlines():
        line = raw
        n_line += 1
        if n_line in doc_lines:
            continue
        if in_block:
            if "*/" not in line:
                continue
            line = line.split("*/", 1)[1]
            in_block = False
        if base.endswith((".ts", ".mjs", ".js", ".go")):
            line = re.sub(r"/\*.*?\*/", "", line)
            if "/*" in line:
                line = line.split("/*", 1)[0]
                in_block = True
        line = strip_comment(line, base)
        if line.strip():
            yield line


def candidates(line: str):
    """줄 전체와, 따옴표·/ 바로 뒤에서 시작하는 꼬리들(앞쪽 [ 가 문자 클래스 파싱을 흩뜨리는 것을 막는다)."""
    yield line
    # 시작점: 따옴표·/ 뒤, 공백 뒤(셸의 따옴표 없는 =~ 우변), =~ 뒤
    starts = [i + 1 for i, c in enumerate(line) if c in "\"'`/ \t=~"][:60]
    for i in starts:
        yield line[i:]


def d_hits(pats, sigs):
    hit = set()
    for x in pats:
        for v in variants(x):
            fp = flat(v)
            for sg, n in sigs.items():
                if sg in fp:  # D-contain
                    hit.add(n)
            hit |= legacy_hits(v)
    return hit


# 대소문자 무시 표지(JS /…/i, Python re.I·IGNORECASE·(?i)): 줄에 있으면 대소문자를 합쳐 한 번 더 비교한다
CI_MARK = re.compile(r"re\.I\b|IGNORECASE|\(\?i\)|/[dgmsuvy]*i[dgmsuvy]*(?![A-Za-z0-9_])")


def fold(f: str) -> str:
    return re.sub(r"\[([^\]]*)\]", lambda m: "[" + "".join(sorted(set(m.group(1)))) + "]", f.lower())


def e_hits(text, base, sigs):
    hit = set()
    for line in code_lines(text, base):
        if "[" not in line and "\\d" not in line and "\\w" not in line:
            continue
        for cand in candidates(line):
            for v in variants(cand):
                f = flat(v)  # E-quant
                for sg, n in sigs.items():
                    if sg in f:
                        hit.add(n)
                hit |= legacy_hits(v)  # E-legacy
                if CI_MARK.search(line):  # E-ci
                    ff = fold(f)
                    hit |= {n for sg, n in sigs.items() if fold(sg) in ff}
    return hit


def generated_header(root, p):
    try:
        with open(root / p, encoding="utf-8") as fh:
            head = [next(fh, "") for _ in range(3)]
    except (OSError, UnicodeDecodeError):
        return False
    return any(GEN_HEADER.match(ln) for ln in head)


def scan(root: pathlib.Path, names, shapes, label, sigs=None, allow=frozenset()):
    r = subprocess.run(["git", "-C", str(root), "ls-files"], capture_output=True, text=True)
    files = [p for p in r.stdout.splitlines() if not SKIP.search(p)] if r.returncode == 0 else []
    bad = []
    for p in files:
        base = p.rsplit("/", 1)[-1]
        stem = re.sub(r"\.(schema\.json|json|d\.ts|ts|py|cjs)$", "", base)
        in_schemas = re.search(r"(^|/)schemas/[^/]+\.json$", p) and not p.startswith("schema/")
        if in_schemas:
            if stem in names:
                bad.append(f"A {label}/{p}: 계약 {stem} 과 이름이 같다")
            try:
                sh = shape(json.loads((root / p).read_text(encoding="utf-8")))
            except ValueError:
                sh = None
            if sh and sh in shapes and shapes[sh] != stem:
                bad.append(f"B {label}/{p}: 계약 {shapes[sh]} 과 칸 구조가 같다(사본)")
        if sigs and f"{label}/{p}" not in allow and not GENERATED.search(p) and not TESTCODE.search(p) and not generated_header(root, p):
            if re.search(r"(^|/)schemas?/.+\.json$", p):
                try:
                    doc = json.loads((root / p).read_text(encoding="utf-8"))
                except (ValueError, UnicodeDecodeError):
                    doc = None
                if doc is not None:
                    hit = sorted(d_hits(list(pattern_nodes(doc)), sigs))
                    if hit:
                        bad.append(f"D {label}/{p}: 계약 {','.join(hit)} 패턴의 사본(같거나 품음, $ref 위임 아님)")
                    fdefs = sorted({k for k, v in defs_nodes(doc) if k in ID_DEFS and isinstance(v, dict)
                                    and not is_contract_ref(v.get("$ref"), names) and "x-contract" not in v})
                    if fdefs:
                        bad.append(f"F {label}/{p}: $defs {','.join(fdefs)} 가 계약 ID 타입 이름인데 계약을 $ref 하지 않는다")
            elif CODE.search(p):
                try:
                    text = (root / p).read_text(encoding="utf-8")
                except (UnicodeDecodeError, OSError):
                    text = ""
                hit = sorted(e_hits(text, base, sigs))
                if hit:
                    bad.append(f"E {label}/{p}: 계약 {','.join(hit)} 패턴의 정규식 사본")
        if not in_schemas and GEN.search(base) and stem in names and "/types/" in "/" + p and "/types/contract/" not in "/" + p:
            bad.append(f"C {label}/{p}: 계약 {stem} 의 생성 타입이 types/contract/ 밖에 있다")
    return len(files), bad


